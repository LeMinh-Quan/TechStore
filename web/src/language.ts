export function translate(language: Language, text: string): string {
  if (language === 'vi') return text
  return translations[text] ?? categoryTranslations[text] ?? text
}

export function translateCategory(language: Language, category: string): string {
  return language === 'en' ? categoryTranslations[category] ?? category : category
}

export function loadLanguage(): Language {
  return localStorage.getItem(languageStorageKey) === 'en' ? 'en' : 'vi'
}
